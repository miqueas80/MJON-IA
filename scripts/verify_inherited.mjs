// Regresión: MJON IA integra herencia preentrenada en su propia interfaz.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const get=p=>readFileSync(resolve(root,p),'utf8');
const html=get('docs/index.html'),app=get('docs/web/app.mjs');
const bridge=get('docs/web/inherited.mjs'),worker=get('docs/web/inherited-worker.mjs');
assert.match(html,/id="inherited-controls"/);
for(const id of ['inherited-load','inherited-release','inherited-precision','inherited-status'])assert.ok(html.includes('id="'+id+'"'));
assert.ok(!html.includes('Universidad MJON')&&!html.includes('open-base.html'),'No crear página independiente');
assert.ok(app.includes("option.value='inherited'"),'Cerebro heredado debe aparecer en selector MJON');
assert.ok(app.includes("await inherited.load(")&&app.includes("await inherited.generate("));
assert.ok(bridge.includes("new Worker(")&&bridge.includes('inherited-worker.mjs'));
assert.ok(worker.includes("onnx-community/Qwen2.5-0.5B-Instruct"));
assert.ok(worker.includes("device: 'webgpu'"));
assert.ok(worker.includes("await import(TRANSFORMERS_URL)"));
assert.ok(worker.includes("env.useBrowserCache = true"));
assert.ok(!/\bfetch\(/.test(bridge),'No se envían prompts a API externa');
assert.ok(!/\bfetch\(/.test(worker),'El motor no realiza fetch manual de prompts');
assert.ok(get('docs/INHERITANCE.md').includes('derivada'));
console.log('MJON herencia neuronal integrada: interfaz única, carga voluntaria y trazabilidad PASS');
